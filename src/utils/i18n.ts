export function formatHTG(amount: number): string {
  return new Intl.NumberFormat('fr-HT', {
    style: 'decimal',
    maximumFractionDigits: 0,
  }).format(amount || 0).replace(/,/g, ' ') + ' HTG';
}

export function formatPrice(amountHTG: number, currency: AppCurrency | string = 'HTG'): string {
  const safeAmount = amountHTG || 0;
  if (currency === 'USD') {
    const usd = (safeAmount / 132.5).toFixed(2);
    return `$${usd} USD`;
  }
  return formatHTG(safeAmount);
}
